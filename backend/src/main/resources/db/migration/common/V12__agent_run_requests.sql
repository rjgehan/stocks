-- =====================================================================================================================
-- V12: "Run now" requests for AI players (ARCHITECTURE §20.9). The bot's owner or the admin asks for a check-in from the
-- app; the claude-trader service claims it with the bot's own key, runs the bot's normal check-in and reports back.
-- Portable H2 2.4 + PostgreSQL 18 (§8 portability rules); com.stocks.agents is the only writer.
-- =====================================================================================================================

CREATE TABLE agent_run_request (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id       VARCHAR(32)   NOT NULL UNIQUE,                 -- arq_<ulid>
  player_id       BIGINT        NOT NULL REFERENCES player(id),  -- the bot
  requested_by    BIGINT        NOT NULL REFERENCES player(id),  -- the human who asked (the owner or the admin)
  requested_at    TIMESTAMP WITH TIME ZONE NOT NULL,
  dry_run         BOOLEAN       NOT NULL,
  status          VARCHAR(8)    NOT NULL CHECK (status IN ('PENDING','CLAIMED','DONE','FAILED','EXPIRED')),
  -- player_id while PENDING or CLAIMED, NULL once final: the unique constraint allows one open request per bot, also
  -- against two requests racing in (both databases allow many NULLs in a UNIQUE column; no partial index needed)
  open_bot_id     BIGINT,
  claimed_at      TIMESTAMP WITH TIME ZONE,
  claimed_key_id  BIGINT        REFERENCES api_key(id),          -- the bot key that claimed it
  finished_at     TIMESTAMP WITH TIME ZONE,
  message         VARCHAR(500),                                  -- the trader's report, or why it expired
  CONSTRAINT ux_agent_run_request_open UNIQUE (open_bot_id),
  CONSTRAINT ck_agent_run_request_open CHECK ((status IN ('PENDING','CLAIMED')) = (open_bot_id IS NOT NULL)),
  CONSTRAINT ck_agent_run_request_bot CHECK (open_bot_id IS NULL OR open_bot_id = player_id),
  CONSTRAINT ck_agent_run_request_claim CHECK (status = 'PENDING' OR status = 'EXPIRED' OR claimed_at IS NOT NULL)
);
-- the latest requests of a bot (newest first) and its requests of the last 24 hours (the daily limit)
CREATE INDEX ix_agent_run_request_player ON agent_run_request(player_id, requested_at);
-- the oldest PENDING request of a bot (the trader's claim)
CREATE INDEX ix_agent_run_request_status ON agent_run_request(player_id, status, requested_at);
