-- §20.6: one row per run the agent runner reported with the bot's own key (POST /api/v1/agent-runs).
CREATE TABLE agent_run (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id           VARCHAR(32)   NOT NULL UNIQUE,         -- arn_<ulid>
  player_id           BIGINT        NOT NULL REFERENCES player(id),
  api_key_id          BIGINT        REFERENCES api_key(id),  -- the key that reported it
  run_ref             VARCHAR(64)   NOT NULL,                -- the runner's id for the run (idempotency)
  run_trigger         VARCHAR(8)    NOT NULL CHECK (run_trigger IN ('SCHEDULE','ONCE')),
  slot                VARCHAR(5),                            -- 'HH:MM' ET of a scheduled run
  model               VARCHAR(100)  NOT NULL,
  status              VARCHAR(24)   NOT NULL CHECK (status IN ('COMPLETED','TOOL_CAP','TIME_CAP','DAILY_CAP',
                        'MAX_TOKENS','REFUSAL','ERROR','ABORTED','SKIPPED_DAILY_CAP','SKIPPED_NON_TRADING_DAY',
                        'SKIPPED_BUSY')),
  started_at          TIMESTAMP WITH TIME ZONE NOT NULL,
  ended_at            TIMESTAMP WITH TIME ZONE NOT NULL,
  trade_date          DATE          NOT NULL,                -- ET date of started_at
  duration_ms         BIGINT        NOT NULL,
  turns               INT           NOT NULL,
  tool_calls          INT           NOT NULL,
  tool_errors         INT           NOT NULL,
  orders_placed       INT           NOT NULL,
  tokens_input        BIGINT        NOT NULL,
  tokens_cache_read   BIGINT        NOT NULL,
  tokens_cache_write  BIGINT        NOT NULL,
  tokens_output       BIGINT        NOT NULL,
  cost_usd            NUMERIC(14,6) NOT NULL,
  day_spent_usd       NUMERIC(14,6) NOT NULL,
  daily_cap_usd       NUMERIC(14,6) NOT NULL,
  message             VARCHAR(500),
  runner_version      VARCHAR(40),
  received_at         TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT ux_agent_run_ref UNIQUE (player_id, run_ref)
);
CREATE INDEX ix_agent_run_player ON agent_run(player_id, started_at);
CREATE INDEX ix_agent_run_date ON agent_run(trade_date);

-- §20.6: tool calls of a run by tool and result code ('OK' or the error code).
CREATE TABLE agent_run_tool (
  run_id       BIGINT       NOT NULL REFERENCES agent_run(id),
  tool         VARCHAR(64)  NOT NULL,
  result_code  VARCHAR(48)  NOT NULL,
  calls        INT          NOT NULL,
  PRIMARY KEY (run_id, tool, result_code)
);

-- §20.7: public notes of AI players, visible after social.tradeFeedDelay.
CREATE TABLE journal_note (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id   VARCHAR(32)   NOT NULL UNIQUE,                 -- jnl_<ulid>
  player_id   BIGINT        NOT NULL REFERENCES player(id),
  body        VARCHAR(600)  NOT NULL,                        -- cleaned text, at most 500 characters
  symbols     VARCHAR(80),                                   -- comma-separated tickers, at most 5
  channel     VARCHAR(16)   NOT NULL,
  created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
  visible_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_journal_player ON journal_note(player_id, created_at);
CREATE INDEX ix_journal_visible ON journal_note(player_id, visible_at);

-- §17.10: API-key traffic aggregated per (UTC hour, key, channel, endpoint, outcome); 90-day retention.
CREATE TABLE api_access_log (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bucket_start  TIMESTAMP WITH TIME ZONE NOT NULL,
  player_id     BIGINT        NOT NULL REFERENCES player(id),
  api_key_id    BIGINT        REFERENCES api_key(id),
  key_ref       VARCHAR(40)   NOT NULL,
  channel       VARCHAR(16)   NOT NULL,
  endpoint      VARCHAR(120)  NOT NULL,
  outcome       VARCHAR(48)   NOT NULL,
  calls         INT           NOT NULL,
  total_ms      BIGINT        NOT NULL,
  max_ms        INT           NOT NULL,
  first_at      TIMESTAMP WITH TIME ZONE NOT NULL,
  last_at       TIMESTAMP WITH TIME ZONE NOT NULL,
  last_ip       VARCHAR(45),
  last_client   VARCHAR(120),
  CONSTRAINT ux_api_access_bucket UNIQUE (bucket_start, key_ref, channel, endpoint, outcome)
);
CREATE INDEX ix_api_access_player ON api_access_log(player_id, last_at);
CREATE INDEX ix_api_access_last ON api_access_log(last_at);
