-- =====================================================================================================================
-- V15: Claude plan usage snapshots. The claude-trader service runs the bots on the owner's Claude subscription; before
-- and after every check-in, and before and after each round of check-ins, it reads the plan's meters (the 5-hour
-- session and the weekly limit, as Claude Code's /usage reports them) and sends them with a bot's own key. The owner
-- sees them under Admin -> Bots. Portable H2 2.4 + PostgreSQL 18 (§8 portability rules); com.stocks.agents is the only
-- writer.
-- =====================================================================================================================

CREATE TABLE plan_usage_snapshot (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_id         BIGINT        NOT NULL REFERENCES player(id),  -- the bot whose key sent it
  kind              VARCHAR(16)   NOT NULL CHECK (kind IN ('CHECKIN_BEFORE','CHECKIN_AFTER','ROUND_BEFORE','ROUND_AFTER')),
  source            VARCHAR(16)   NOT NULL CHECK (source IN ('USAGE','CHECKIN')),
  taken_at          TIMESTAMP WITH TIME ZONE NOT NULL,
  trade_date        DATE          NOT NULL,                        -- the ET date of taken_at
  round_ref         VARCHAR(64),                                   -- the trader's id of the round (both kinds)
  run_ref           VARCHAR(64),                                   -- the trader's id of the check-in (CHECKIN_*)
  session_percent   DECIMAL(5,1),                                  -- 0-100; NULL when the plan did not say
  session_resets_at TIMESTAMP WITH TIME ZONE,
  weekly_percent    DECIMAL(5,1),
  weekly_resets_at  TIMESTAMP WITH TIME ZONE,
  tokens_input      BIGINT,                                        -- CHECKIN_AFTER: the check-in's own usage
  tokens_cache_write BIGINT,
  tokens_cache_read BIGINT,
  tokens_output     BIGINT,
  cost_usd          DECIMAL(12,4),                                 -- Claude Code's API-price estimate (not billed)
  received_at       TIMESTAMP WITH TIME ZONE NOT NULL
);
-- the newest snapshots (the panel), and a bot's snapshots of the last 24 hours (the report budget)
CREATE INDEX ix_plan_usage_taken ON plan_usage_snapshot(taken_at);
CREATE INDEX ix_plan_usage_player ON plan_usage_snapshot(player_id, received_at);
