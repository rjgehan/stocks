  max_per_order   NUMERIC(19,2),
  effective_from  DATE           NOT NULL,
  effective_to    DATE,                                -- inclusive; NULL = open-ended
  source_note     VARCHAR(300)   NOT NULL,
  CHECK (effective_to IS NULL OR effective_to >= effective_from)
);
