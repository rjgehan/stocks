-- =====================================================================================================================
-- V7 (provisional number; the integrator renumbers at merge): OAuth 2.1 authorization server for the claude.ai and
-- ChatGPT connectors (ARCHITECTURE §17.9.6). Portable H2 2.4 + PostgreSQL 18 (no TEXT/jsonb/partial indexes).
-- Every secret is stored as a SHA-256 hash (codes, refresh tokens, DCR client secrets); the signing key is stored
-- AES-GCM encrypted under a key derived from API_KEY_PEPPER.
-- =====================================================================================================================

-- DCR registrations (RFC 7591). CIMD clients are fetched from their client_id URL and never stored here.
CREATE TABLE oauth_client (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id       VARCHAR(40)   NOT NULL UNIQUE,                 -- ocl_<ULID>
  client_name     VARCHAR(100)  NOT NULL,
  redirect_uris   VARCHAR(4000) NOT NULL,                        -- JSON array of allowlisted URIs
  grant_types     VARCHAR(64)   NOT NULL,                        -- space-separated ⊆ 'authorization_code refresh_token'
  auth_method     VARCHAR(24)   NOT NULL CHECK (auth_method IN ('none','client_secret_basic','client_secret_post')),
  secret_hash     VARCHAR(64),                                   -- hex SHA-256 of the client secret (confidential only)
  registered_ip   VARCHAR(45),
  user_agent      VARCHAR(300),
  created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
  last_used_at    TIMESTAMP WITH TIME ZONE,
  CONSTRAINT ck_oauth_client_secret CHECK ((auth_method = 'none') = (secret_hash IS NULL))
);
CREATE INDEX ix_oauth_client_created ON oauth_client(created_at);

-- /oauth2/authorize requests waiting for login + the act-as consent (15 minutes).
CREATE TABLE oauth_authorization_request (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id      VARCHAR(40)   NOT NULL UNIQUE,                 -- oar_<32 random base64url chars>, in the consent URL
  client_id       VARCHAR(512)  NOT NULL,
  client_kind     VARCHAR(4)    NOT NULL CHECK (client_kind IN ('CIMD','DCR')),
  client_name     VARCHAR(100)  NOT NULL,
  client_host     VARCHAR(255)  NOT NULL,
  redirect_uri    VARCHAR(1000) NOT NULL,
  scopes          VARCHAR(128)  NOT NULL,                        -- requested, filtered to the four API scopes
  offline_access  BOOLEAN       NOT NULL,
  state           VARCHAR(2000),
  code_challenge  VARCHAR(128)  NOT NULL,                        -- S256 only
  resource        VARCHAR(500)  NOT NULL,
  created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
  expires_at      TIMESTAMP WITH TIME ZONE NOT NULL,
  consumed_at     TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_oauth_request_expires ON oauth_authorization_request(expires_at);

-- One row per consent: the authorization code and the refresh-token family hang off it.
CREATE TABLE oauth_grant (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id        VARCHAR(32)   NOT NULL UNIQUE,                -- ogr_<ULID>; the JWT's gid claim
  client_id        VARCHAR(512)  NOT NULL,
  client_kind      VARCHAR(4)    NOT NULL CHECK (client_kind IN ('CIMD','DCR')),
  client_name      VARCHAR(100)  NOT NULL,
  client_host      VARCHAR(255)  NOT NULL,
  redirect_uri     VARCHAR(1000) NOT NULL,
  human_player_id  BIGINT        NOT NULL REFERENCES player(id), -- who consented
  actor_player_id  BIGINT        NOT NULL REFERENCES player(id), -- whom the tokens act as (the human or a bot they own)
  scopes           VARCHAR(128)  NOT NULL,
  resource         VARCHAR(500)  NOT NULL,
  refresh_allowed  BOOLEAN       NOT NULL,
  code_hash        VARCHAR(64)   NOT NULL UNIQUE,                -- hex SHA-256 of the one-time authorization code
  code_challenge   VARCHAR(128)  NOT NULL,
  code_expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
  code_used_at     TIMESTAMP WITH TIME ZONE,
  created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
  last_used_at     TIMESTAMP WITH TIME ZONE,
  revoked_at       TIMESTAMP WITH TIME ZONE,
  revoke_reason    VARCHAR(16)   CHECK (revoke_reason IN ('USER','CLIENT','REUSE','CODE_REUSE','OWNER_CHANGED',
                                                         'PLAYER_DISABLED')),
  CONSTRAINT ck_oauth_grant_revoked CHECK ((revoked_at IS NULL) = (revoke_reason IS NULL))
);
CREATE INDEX ix_oauth_grant_human ON oauth_grant(human_player_id);
CREATE INDEX ix_oauth_grant_actor ON oauth_grant(actor_player_id);
CREATE INDEX ix_oauth_grant_client ON oauth_grant(client_id);

-- Rotating refresh tokens; a rotated token presented again revokes its grant (reuse detection).
CREATE TABLE oauth_refresh_token (
  token_hash  VARCHAR(64) PRIMARY KEY,                           -- hex SHA-256 of ort_<secret>
  grant_id    BIGINT      NOT NULL REFERENCES oauth_grant(id),
  created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
  expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
  rotated_at  TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_oauth_refresh_grant ON oauth_refresh_token(grant_id);
CREATE INDEX ix_oauth_refresh_expires ON oauth_refresh_token(expires_at);

-- The access-token signing key when OAUTH_JWK_PEM_FILE is not set: generated on first boot, encrypted at rest.
CREATE TABLE oauth_signing_key (
  kid              VARCHAR(64)   PRIMARY KEY,                    -- RFC 7638 thumbprint
  public_jwk       VARCHAR(2000) NOT NULL,                       -- JSON
  private_key_enc  VARCHAR(4000) NOT NULL,                       -- base64(IV || AES-256-GCM(PKCS#8 DER))
  created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
  retired_at       TIMESTAMP WITH TIME ZONE
);
