-- V3 (WS3, Phase 2 wave A; number final since the wave A integration merge, §8 "As deployed"):
-- group orders (§11.9: OCO, OTO, OTOCO, BRACKET), the FINRA 5330 do-not-reduce flag (§14) and cancel latency
-- (§11.10: PENDING_CANCEL is an API status; the stored status stays WORKING / PARTIALLY_FILLED).
-- Portable H2 2.4 + PostgreSQL 18 (§8 portability rules): no PG-only types, constraints added by name.

CREATE TABLE order_group (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id        VARCHAR(32)   NOT NULL UNIQUE,
  account_id       BIGINT        NOT NULL REFERENCES account(id),
  player_id        BIGINT        NOT NULL REFERENCES player(id),
  client_order_id  VARCHAR(64)   NOT NULL,
  request_hash     VARCHAR(64)   NOT NULL,
  group_type       VARCHAR(8)    NOT NULL CHECK (group_type IN ('OCO','OTO','OTOCO','BRACKET')),
  symbol           VARCHAR(12)   NOT NULL,
  qty              NUMERIC(18,5) NOT NULL CHECK (qty > 0),
  time_in_force    VARCHAR(4)    NOT NULL CHECK (time_in_force IN ('DAY','GTC')),
  created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
  version          BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT ux_order_group_client_id UNIQUE (account_id, client_order_id)
);
CREATE INDEX ix_order_group_account ON order_group(account_id, created_at);

-- Every group clientOrderId ever used (the placement's and each group replace's), so a retry of either replays even
-- after a replace gave the group a new id (§11.9 idempotency).
CREATE TABLE order_group_request (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id       BIGINT        NOT NULL REFERENCES account(id),
  group_id         BIGINT        NOT NULL REFERENCES order_group(id),
  client_order_id  VARCHAR(64)   NOT NULL,
  request_hash     VARCHAR(64)   NOT NULL,
  kind             VARCHAR(8)    NOT NULL CHECK (kind IN ('PLACE','REPLACE')),
  created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT ux_order_group_request UNIQUE (account_id, client_order_id)
);
CREATE INDEX ix_order_group_request_group ON order_group_request(group_id);

